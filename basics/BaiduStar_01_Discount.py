"""
原题 - 餐馆会员充值折扣（Discount）

问题描述：
学皇来到了一个餐馆吃饭。他觉得这家餐馆很好吃，于是就想办个会员。
一共有 n 种会员充值卡套餐，假设学皇这餐饭的消费为 a 元，选择第 i 种套餐，
需要充值 b[i] * a 的钱，这次吃饭可以打 c[i] * 10 折，
由充值的钱支付（即这次吃饭只需要从充值金额中扣除 a * c[i] 元）。
以后用剩余的充值的钱吃饭不再打折。
请问学皇应该选择哪个套餐（必须选择恰好一个套餐），使得优惠的比例最大？
优惠比例的定义是：把充的钱用完以后，
(本来应该付的钱 - 实际付的钱) / 本来应该付的钱。
在这个题目里，实际付的钱就是这次充值的花费。

输入格式：
第一行一个整数 test (1 <= test <= 100) 表示数据组数。
对于每组数据，第一行一个正整数 n (1 <= n <= 100) 表示套餐的数目。
接下来 n 行，每行一个正整数 b[i] (1 <= b[i] <= 100) 和
一个小数 c[i] (0 <= c[i] <= 1，c[i] 最多包含两位小数)。

输出格式：
对于每组数据，输出一个五位小数表示最大的优惠比例。
如果小数点后超过五位，四舍五入到五位。

样例输入：
1
2
2 0.5
3 0.1

样例输出：
0.23077

核心推导公式（本题专用）：
pay = a + a * b[i] - a * c[i];practical_pay = a * b [i] - a * c[i];
rate = (pay - practical_pay) / pay)
每个套餐的优惠比例只与 b 和 c 有关，计算公式为 (1.0 - c) / (1.0 + b - c)。
只需要遍历所有套餐，输出这个公式计算结果的最大值。

"""
def Count_PayRate(x,y):
    """计算优惠比例函数"""
    Rate = (1.0 - y) / (1.0 + x - y)
    return Rate
