import math

# 实验参数设置
d = 0.5 / 100  # 挡光片宽度，转换为米 (0.005m)
s = 50.0 / 100 # 两个光电门之间的距离，转换为米 (0.5m)

# 原始时间数据 (单位：ms)
raw_data = {
    "垫一个垫块": [
        [75.97, 69.00, 37.57, 36.70],
        [75.76, 68.90, 37.94, 37.07],
        [76.16, 69.47, 38.02, 37.18],
        [75.62, 68.94, 38.19, 37.32]
    ],
    "垫两个垫块": [
        [32.03, 29.21, 16.02, 15.65],
        [32.99, 30.10, 16.09, 15.68],
        [34.80, 32.24, 17.16, 16.68],
        [32.08, 29.37, 16.77, 16.31],
        [34.40, 30.93, 16.17, 15.76]
    ],
    "垫三个垫块": [
        [26.23, 23.83, 12.88, 12.57],
        [26.20, 23.83, 12.88, 12.57],
        [26.16, 23.78, 12.89, 12.59],
        [26.32, 23.93, 12.93, 12.62],
        [27.79, 24.98, 13.03, 12.72]
    ],
    "垫四个垫块": [
        [22.57, 20.52, 11.11, 10.85],
        [22.80, 20.69, 11.16, 10.88],
        [22.74, 20.67, 11.18, 10.92],
        [21.97, 20.09, 11.12, 10.87],
        [22.84, 20.77, 11.22, 10.96]
    ]
}

print(f"{'实验组别':<15} | {'第1次 a (m/s²)':<15} | {'第2次 a (m/s²)':<15} | {'平均 a (m/s²)':<15}")
print("-" * 75)

for group_name, trials in raw_data.items():
    print(f"\n【{group_name}】")
    group_accelerations = []
    
    for i, times in enumerate(trials):
        # 将时间转换为秒
        t1, t2, t3, t4 = [t / 1000 for t in times]
        
        # 计算经过两个光电门的瞬时速度 (v = d / t)
        v1, v2 = d / t1, d / t2
        v3, v4 = d / t3, d / t4
        
        # 计算加速度 (a = (v2^2 - v1^2) / 2s)，用 math.pow 替代 ** 运算符
        a1 = (math.pow(v2, 2) - math.pow(v1, 2)) / (2 * s)
        a2 = (math.pow(v4, 2) - math.pow(v3, 2)) / (2 * s)
        avg_a = (a1 + a2) / 2
        
        group_accelerations.append(avg_a)
        print(f"第{i+1}次实验: {a1:.4f}        {a2:.4f}        {avg_a:.4f}")
        
    # 使用 Python 内置的 sum() 和 len() 计算平均值，替代 numpy.mean
    overall_avg = sum(group_accelerations) / len(group_accelerations)
    print(f"👉 {group_name} 的最终平均加速度 a = {overall_avg:.4f} m/s²")
    print("-" * 30)
